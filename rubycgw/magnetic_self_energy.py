"""Gauge-invariant uniform-magnetic-field self-energy response for supercell GW.

This module implements the second ingredient entering Nourafkan, Kotliar, and
Tremblay, Phys. Rev. B 90, 125132 (2014), Eq. (2):

    Sigma_b = d Sigma_tilde^(B) / db |_{b=0},

with the dimensionless magnetic variable

    b = (e a^2 / hbar) B_z.

The derivation follows their Appendix A, Eq. (A13).  After the Peierls phase is
factored from G and Sigma, the gauge-invariant Green function obeys to first
order in a uniform B field

    G_b = Y_b + G Sigma_b G,

where the geometric magnetic source is

    Y_b = -(i/2) [ G J_x G J_y G - G J_y G J_x G ],

and

    J_alpha = -D_alpha G^{-1}.

For self-consistent GW the field derivative of the self-energy is obtained by
linearizing the same zero-field GW functional:

    Sigma_b = C_GW[G_b],

where C_GW[X] contains the Hartree, static-Fock, MT and AL pieces generated by
an arbitrary Green-function tangent X.  Consequently

    (I-L_GW) Sigma_b = C_GW[Y_b],

with

    L_GW[S] = C_GW[G S G].

This is solved with the same matrix-free restarted GMRES infrastructure as the
q=0 covariant-GW vertex equation.  No finite magnetic supercell and no finite-B
subtraction are required.

The interaction is density-density and has no explicit linear magnetic-field
coupling.  Thus all linear field dependence of the gauge-invariant GW
self-energy comes through G_b, consistent with the diagrammatic statement in
footnote 28 of Nourafkan et al.
"""

