#!/usr/bin/env python3
"""Evaluate cGW and thermodynamics at every target-V crossing of a PMS branch.

Input is the checkpoint/archive generated by
``scan_fierz_pms_pseudo_arclength.py``.  Each target candidate is refined at
exactly fixed V with the augmented equations

    R_GW = 0,
    dF_GW/dlambda = 0,

then deduplicated.  The resulting lambda_*(V), Fierz curvature, Green-function
error, q=0 cGW current susceptibilities, and GW/ED free energies are reported
for every distinct PMS root.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np

from benchmark_fierz_weighted_pac_target import (
    _green_errors,
    _infer_states_path,
    _load_or_compute_ed,
    _physical_chi,
    _relerr,
    _root_distance,
    _source_segment,
)
from rubycgw.branch_state_archive import find_target_crossings, load_branch_state_archive
from rubycgw.fierz_channel_gw import (
    ChannelGWResult,
    channel_static_self_energy,
    solve_channel_vertex_q0,
    susceptibility_from_vertex_q0,
)
from rubycgw.fierz_mixed import (
    build_weighted_nbj_definition,
    soft_mode_sector_fractions,
    weights_from_lambda,
)
from rubycgw.fierz_pac import soft_mode_overlap
from rubycgw.fierz_pms import WeightedFierzPMSResidual
from rubycgw.grids import MatsubaraGrid
from rubycgw.model import RubyParameters
from rubycgw.pseudo_arclength import PACOptions, refine_fixed_parameter
from rubycgw.small_cluster_exact import ExactSmallRubyThermal
from rubycgw.supercell_cgw import SupercellVertexOptions


CHANNELS = ("z_same", "z_opposite")


def _args():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--states", type=Path, default=None)
    p.add_argument("--V", type=float, required=True)
    p.add_argument("--crossing-atol", type=float, default=1e-10)
    p.add_argument("--root-dedup-rtol", type=float, default=1e-7)
    p.add_argument("--newton-tol", type=float, default=1e-10)
    p.add_argument("--newton-max", type=int, default=20)
    p.add_argument("--fd-eps", type=float, default=3e-7)
    p.add_argument("--gmres-rtol", type=float, default=5e-4)
    p.add_argument("--gmres-maxiter", type=int, default=90)
    p.add_argument("--gmres-restart", type=int, default=22)
    p.add_argument("--line-search-min", type=float, default=1.0 / 4096.0)
    p.add_argument("--screening-floor", type=float, default=1e-8)
    p.add_argument("--vertex-max-iter", type=int, default=300)
    p.add_argument("--vertex-tol", type=float, default=1e-8)
    p.add_argument("--vertex-gmres-restart", type=int, default=16)
    p.add_argument("--low-count", type=int, default=8)
    p.add_argument("--skip-ed", action="store_true")
    p.add_argument("--refresh-ed-cache", action="store_true")
    p.add_argument("--ed-cache-dir", type=Path, default=Path("results/ed_cache"))
    p.add_argument("--out", type=Path, default=Path("results/ed_fierz_pms_cgw"))
    p.add_argument("--verbose", action="store_true")
    return p.parse_args()


def _make_background(problem, definition, y, ev, root):
    sigma_static, sigma_c, mu, _, _ = problem.decode(y)
    _, tad, exchange = channel_static_self_energy(ev.rho, definition)
    return ChannelGWResult(
        G=np.asarray(ev.G),
        W=np.asarray(ev.W),
        P=np.asarray(ev.P),
        Sigma_static=np.asarray(sigma_static),
        Sigma_tadpole=np.asarray(tad),
        Sigma_exchange=np.asarray(exchange),
        Sigma_c=np.asarray(sigma_c),
        mu=float(mu),
        rho=np.asarray(ev.rho),
        density=np.real(np.diag(ev.rho)),
        converged=bool(root.converged),
        iterations=int(root.newton_iterations),
        final_error=float(ev.physical_residual),
        mixing_method="newton-krylov-pms",
        mode=definition.mode,
        min_screening_singular_value=float(ev.smin),
    )


def _write_csv(path: Path, rows):
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def main():
    args = _args()
    with np.load(args.checkpoint, allow_pickle=False) as data:
        signature = str(np.asarray(data["signature"]).item())
        meta = json.loads(signature)

    required = (
        "mode", "L1", "L2", "filling", "target", "T", "ti", "t1", "t2",
        "nw", "nomega", "norb", "lambda_fd_h", "lambda_margin", "pms_scale_floor",
    )
    missing = [k for k in required if k not in meta]
    if missing:
        raise RuntimeError(f"PMS checkpoint signature missing keys: {missing}")
    if str(meta["mode"]).lower() != "weighted_nbj_pms":
        raise RuntimeError("checkpoint is not from scan_fierz_pms_pseudo_arclength.py")

    V_target = float(args.V)
    target_N = float(meta["target"])
    npc = int(meta["L1"]) * int(meta["L2"])
    states_path = args.states if args.states is not None else _infer_states_path(args.checkpoint)
    if not states_path.exists():
        raise RuntimeError(f"PMS full-state archive not found: {states_path}")

    params = RubyParameters(
        ti=float(meta["ti"]), t1=float(meta["t1"]), t2=float(meta["t2"]), V=0.0
    )
    geometry = ExactSmallRubyThermal(int(meta["L1"]), int(meta["L2"]), params)
    norb = int(geometry.n_sites)
    grid = MatsubaraGrid(
        nk1=1, nk2=1, nw=int(meta["nw"]), nOmega=int(meta["nomega"]), T=float(meta["T"])
    )
    h0 = np.asarray(geometry.h0, dtype=complex)[None, None]
    problem = WeightedFierzPMSResidual(
        h0,
        geometry.interaction_pairs,
        grid,
        target_N,
        primitive_cells=npc,
        lambda_fd_h=float(meta["lambda_fd_h"]),
        lambda_margin=float(meta["lambda_margin"]),
        free_energy_scale_floor=float(meta["pms_scale_floor"]),
    )
    archive = load_branch_state_archive(
        states_path,
        expected_signature=signature,
        expected_state_size=problem.codec.size,
    )
    crossings = find_target_crossings(archive, V_target, atol=float(args.crossing_atol))
    if not crossings:
        raise RuntimeError(f"PMS archive contains no crossing of V={V_target:g}")

    print("=== Exact-target self-consistent Fierz PMS + cGW + free energy ===")
    print(
        f"target V={V_target:g}, candidates={len(crossings)}, archive states={archive.nstate}, "
        f"V range=[{np.min(archive.V):.9g},{np.max(archive.V):.9g}]"
    )

    def guarded_residual(y, V):
        ev = problem.evaluate(y, V)
        if ev.smin < float(args.screening_floor):
            raise FloatingPointError("screening matrix below numerical floor")
        return ev.residual

    opts = PACOptions(
        tol=args.newton_tol,
        max_newton=args.newton_max,
        fd_eps=args.fd_eps,
        gmres_rtol=args.gmres_rtol,
        gmres_maxiter=args.gmres_maxiter,
        gmres_restart=args.gmres_restart,
        line_search_min=args.line_search_min,
        verbose=args.verbose,
    )

    roots = []
    failures = []
    duplicate_count = 0
    for ic, crossing in enumerate(crossings):
        root = refine_fixed_parameter(
            np.asarray(crossing.x_guess, dtype=float), V_target, guarded_residual, opts=opts
        )
        if not root.converged:
            failures.append(ic)
            print(f"candidate {ic} FAILED: |R|={root.residual_norm:.3e}")
            continue
        ev = problem.evaluate(root.x, V_target)
        duplicate_of = None
        for ir, item in enumerate(roots):
            if _root_distance(root.x, item["root"].x) < float(args.root_dedup_rtol):
                duplicate_of = ir
                break
        if duplicate_of is not None:
            duplicate_count += 1
            roots[duplicate_of]["sources"].append(_source_segment(crossing))
            print(f"candidate {ic} -> duplicate of PMS root {duplicate_of}")
            continue
        roots.append({
            "root": root,
            "ev": ev,
            "crossing": crossing,
            "candidate": ic,
            "sources": [_source_segment(crossing)],
        })
        print(
            f"candidate {ic} -> root {len(roots)-1}: lambda*={ev.lambda_value:.9f}, "
            f"dF/dlambda/cell={ev.dF_dlambda_per_cell:+.3e}, "
            f"curvature/cell={ev.d2F_dlambda2_per_cell:+.3e}, "
            f"phys={ev.physical_residual:.3e}, smin={ev.smin:.3e}"
        )
    if not roots:
        raise RuntimeError("all PMS target candidates failed refinement")

    operators = np.stack([
        np.asarray(geometry.pseudospin_operator(ch, (0.0, 0.0)), dtype=complex)
        for ch in CHANNELS
    ])
    Ged, chi_ed, mu_ed, ed_cache_path, ed_thermo = _load_or_compute_ed(
        args, meta, geometry, operators, grid, V_target, norb
    )
    if ed_thermo is not None:
        print(
            f"ED: mu={mu_ed:+.10f}, F/cell={ed_thermo['F_pc']:+.12e}, "
            f"chi=({chi_ed[0,0]:.9f},{chi_ed[1,1]:.9f})"
        )

    vopts = SupercellVertexOptions(
        max_iter=args.vertex_max_iter,
        tol=args.vertex_tol,
        solver="gmres",
        gmres_restart=args.vertex_gmres_restart,
        verbose=args.verbose,
        momentum_backend="direct",
    )

    rows = []
    for ir, item in enumerate(roots):
        root = item["root"]
        ev = item["ev"]
        sigma_static, sigma_c, mu, lam, u = problem.decode(root.x)
        weights = weights_from_lambda(lam)
        definition = build_weighted_nbj_definition(
            geometry.interaction_pairs, norb, V_target, weights
        )
        bg = _make_background(problem, definition, root.x, ev, root)
        frac = soft_mode_sector_fractions(definition, ev.soft_mode)
        overlap = [soft_mode_overlap(K, definition, ev.soft_mode) for K in operators]
        thermo = ev.free_energy

        print(f"\n=== PMS root {ir}/{len(roots)-1} ===")
        print(
            f"lambda*={lam:.10f}, weights=(n,B,J)=({weights.density:.6f},"
            f"{weights.bond:.6f},{weights.current:.6f}), mu={mu:+.10f}"
        )
        print(
            f"dF/dlambda/cell={ev.dF_dlambda_per_cell:+.3e}, "
            f"curvature/cell={ev.d2F_dlambda2_per_cell:+.6e}, "
            f"F/cell={thermo.free_energy_per_primitive_cell:+.12e}"
        )
        print(
            f"smin={ev.smin:.3e}, soft m={ev.soft_m:+d}, "
            f"sector(n,B,J)=({frac['n']:.6f},{frac['B']:.6f},{frac['J']:.6f}), "
            f"overlap(same,opp)=({overlap[0]:.6f},{overlap[1]:.6f})"
        )

        chi_raw = np.full((2, 2), np.nan + 0j, dtype=complex)
        vertex_res = []
        vertex_ok = True
        for b, (name, Ksrc) in enumerate(zip(CHANNELS, operators)):
            print(f"PMS root {ir} cGW vertex: {name} ...")
            vr = solve_channel_vertex_q0(bg, definition, Ksrc, grid, opts=vopts)
            vertex_res.append(float(vr.final_error))
            if not vr.converged:
                vertex_ok = False
                print(f"WARNING: vertex {name} failed: residual={vr.final_error:.3e}")
                break
            for a, Kleft in enumerate(operators):
                chi_raw[a, b] = susceptibility_from_vertex_q0(bg.G, Kleft, vr.Gamma, grid)
        if vertex_ok:
            chi, chi_imag = _physical_chi(chi_raw)
        else:
            chi = np.full((2, 2), np.nan)
            chi_imag = np.nan

        gerr = gerr_low = chi_err = np.nan
        F_minus_ed = F_minus_ed_pc = np.nan
        if Ged is not None:
            gerr, gerr_low = _green_errors(bg.G, Ged, grid, args.low_count)
            if vertex_ok:
                chi_err = _relerr(chi, chi_ed)
            if ed_thermo is not None:
                F_minus_ed = thermo.helmholtz_free_energy - ed_thermo["F"]
                F_minus_ed_pc = thermo.free_energy_per_primitive_cell - ed_thermo["F_pc"]
        print(
            f"chi(same,opp)=({chi[0,0]:+.9f},{chi[1,1]:+.9f}), "
            f"Gerr={gerr:.6e}, chi_relerr={chi_err:.6e}, "
            f"F-F_ED/cell={F_minus_ed_pc:+.6e}"
        )

        item.update({
            "lambda": lam,
            "mu": mu,
            "sigma_static": np.asarray(sigma_static),
            "sigma_c": np.asarray(sigma_c),
            "bg": bg,
            "definition": definition,
            "frac": frac,
            "overlap": np.asarray(overlap),
            "chi": np.asarray(chi),
            "chi_raw": np.asarray(chi_raw),
            "chi_imag": chi_imag,
            "vertex_max_residual": max(vertex_res) if vertex_res else np.nan,
            "gerr": gerr,
            "gerr_low": gerr_low,
            "chi_err": chi_err,
            "F_minus_ed": F_minus_ed,
            "F_minus_ed_pc": F_minus_ed_pc,
        })
        rows.append({
            "root": ir,
            "candidate": item["candidate"],
            "source_crossings": len(item["sources"]),
            "lambda_star": f"{lam:.16g}",
            "lambda_n": f"{weights.density:.16g}",
            "lambda_B": f"{weights.bond:.16g}",
            "lambda_J": f"{weights.current:.16g}",
            "mu": f"{mu:.16g}",
            "dF_dlambda_per_cell": f"{ev.dF_dlambda_per_cell:.8e}",
            "d2F_dlambda2_per_cell": f"{ev.d2F_dlambda2_per_cell:.8e}",
            "F_GW_per_cell": f"{thermo.free_energy_per_primitive_cell:.16g}",
            "F_ED_per_cell": f"{ed_thermo['F_pc']:.16g}" if ed_thermo is not None else "nan",
            "F_minus_ED_per_cell": f"{F_minus_ed_pc:.16g}",
            "chi_same": f"{chi[0,0]:.16g}",
            "chi_opposite": f"{chi[1,1]:.16g}",
            "Gerr": f"{gerr:.8e}",
            "Gerr_low": f"{gerr_low:.8e}",
            "chi_relerr": f"{chi_err:.8e}",
            "smin": f"{ev.smin:.8e}",
            "soft_n": f"{frac['n']:.8e}",
            "soft_B": f"{frac['B']:.8e}",
            "soft_J": f"{frac['J']:.8e}",
            "physical_residual": f"{ev.physical_residual:.8e}",
        })

    args.out.mkdir(parents=True, exist_ok=True)
    tag = f"V{V_target:g}_fill{float(meta['filling']):g}_{int(meta['L1'])}x{int(meta['L2'])}_nbj_pms_allcrossings"
    outfile = args.out / f"{tag}.npz"
    csvfile = args.out / f"{tag}.csv"
    np.savez_compressed(
        outfile,
        V=V_target,
        mode=np.asarray("weighted_nbj_pms"),
        nroot=len(roots),
        candidate_count=len(crossings),
        failed_candidate_count=len(failures),
        duplicate_candidate_count=duplicate_count,
        lambda_star=np.asarray([x["lambda"] for x in roots]),
        lambda_n=np.asarray([x["lambda"] for x in roots]),
        lambda_B=np.asarray([0.5 * (1.0 - x["lambda"]) for x in roots]),
        lambda_J=np.asarray([0.5 * (1.0 - x["lambda"]) for x in roots]),
        dF_dlambda_per_cell=np.asarray([x["ev"].dF_dlambda_per_cell for x in roots]),
        d2F_dlambda2_per_cell=np.asarray([x["ev"].d2F_dlambda2_per_cell for x in roots]),
        F_gw=np.asarray([x["ev"].free_energy.helmholtz_free_energy for x in roots]),
        F_gw_per_cell=np.asarray([x["ev"].free_energy.free_energy_per_primitive_cell for x in roots]),
        mu=np.asarray([x["mu"] for x in roots]),
        X_target=np.stack([x["root"].x for x in roots]),
        Sigma_static=np.stack([x["sigma_static"] for x in roots]),
        Sigma_c=np.stack([x["sigma_c"] for x in roots]),
        G=np.stack([x["bg"].G for x in roots]),
        P=np.asarray([x["bg"].P for x in roots], dtype=object) if False else np.stack([x["bg"].P for x in roots]),
        W=np.stack([x["bg"].W for x in roots]),
        chi=np.stack([x["chi"] for x in roots]),
        chi_raw=np.stack([x["chi_raw"] for x in roots]),
        gerr=np.asarray([x["gerr"] for x in roots]),
        gerr_low=np.asarray([x["gerr_low"] for x in roots]),
        chi_err=np.asarray([x["chi_err"] for x in roots]),
        F_ed=float(ed_thermo["F"]) if ed_thermo is not None else np.nan,
        F_ed_per_cell=float(ed_thermo["F_pc"]) if ed_thermo is not None else np.nan,
        mu_ed=float(mu_ed),
        G_ed=np.asarray(Ged) if Ged is not None else np.empty((0,), dtype=complex),
        chi_ed=np.asarray(chi_ed) if chi_ed is not None else np.empty((0,), dtype=float),
        source_checkpoint=np.asarray(str(args.checkpoint)),
        source_states=np.asarray(str(states_path)),
        ed_cache_path=np.asarray(ed_cache_path),
    )
    _write_csv(csvfile, rows)

    print("\n=== PMS target summary ===")
    for row in rows:
        print(
            f"root {row['root']}: lambda*={row['lambda_star']}, "
            f"curv={row['d2F_dlambda2_per_cell']}, "
            f"chi=({row['chi_same']},{row['chi_opposite']}), "
            f"Gerr={row['Gerr']}, F-F_ED/cell={row['F_minus_ED_per_cell']}"
        )
    print(f"saved {outfile}")
    print(f"saved {csvfile}")
    print(
        "NOTE: a PMS stationary point is not selected by minimizing F across Fierz choices; "
        "the curvature only diagnoses local Fierz sensitivity."
    )


if __name__ == "__main__":
    main()
